// ---- Currency configuration ----
export type Currency = 'USD' | 'GBP' | 'EUR' | 'RUB';
export const CURRENCY_KEYS: Currency[] = ['USD', 'GBP', 'EUR', 'RUB'];
export const CURRENCIES: Record<Currency, { symbol: string; label: string; min: number; max: number; step: number; default: number; region: string }> = {
  USD: { symbol: '$', label: 'USD ($)', min: 30, max: 500, step: 10, default: 100, region: 'the United States' },
  GBP: { symbol: '£', label: 'GBP (£)', min: 25, max: 400, step: 10, default: 90, region: 'the United Kingdom' },
  EUR: { symbol: '€', label: 'EUR (€)', min: 30, max: 450, step: 10, default: 100, region: 'Europe' },
  RUB: { symbol: '₽', label: 'RUB (₽)', min: 1000, max: 20000, step: 500, default: 5000, region: 'Russia' },
};

// ---- Unit system configuration ----
export type UnitSystem = 'metric' | 'imperial';
export const METRIC_UNIT_KEYS: (keyof Dict['units'])[] = ['g', 'kg', 'pcs', 'ml', 'l'];
export const IMPERIAL_UNIT_KEYS: (keyof Dict['units'])[] = ['oz', 'lb', 'pcs', 'floz', 'cup'];

export function formatMoney(amount: number, currency: Currency, locale: string): string {
  const c = CURRENCIES[currency] ?? CURRENCIES.RUB;
  const num = Math.round(amount ?? 0).toLocaleString(locale);
  return currency === 'RUB' ? `${num} ${c.symbol}` : `${c.symbol}${num}`;
}

export function interpolate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
